// Generates the API types from the committed OpenAPI documents (change api-contract-types, design D2).
//   npm run gen:api    writes src/api/generated/<service>.ts
//   npm run check:api  fails when a committed file differs from what the documents produce
// Only public.json is read: internal.json describes operations the gateway does not route.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

export const SERVICES = ['auth', 'catalog', 'customer', 'order', 'inventory', 'delivery'] as const;

const frontendDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = resolve(frontendDir, '..');
const outDir = join(frontendDir, 'src', 'api', 'generated');

function sourcePath(service: string): string {
  return join(repoDir, `${service}-service`, 'openapi', 'public.json');
}

function outPath(service: string): string {
  return join(outDir, `${service}.ts`);
}

/** The generated file for one service, with LF line endings. */
async function generate(service: string): Promise<string> {
  const source = sourcePath(service);
  if (!existsSync(source)) throw new Error(`Missing OpenAPI document: ${source}`);
  const ast = await openapiTS(pathToFileURL(source));
  const header = [
    '/**',
    ' * This file was auto-generated by openapi-typescript (npm run gen:api).',
    ' * Do not make direct changes to the file.',
    ` * Source: ${relative(frontendDir, source).replaceAll('\\', '/')}`,
    ' */',
    '',
    '',
  ].join('\n');
  return (header + astToString(ast)).replace(/\r\n/g, '\n');
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check');
  const stale: string[] = [];
  mkdirSync(outDir, { recursive: true });

  for (const service of SERVICES) {
    const content = await generate(service);
    const target = outPath(service);
    if (check) {
      const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
      if (current !== content) stale.push(relative(frontendDir, target).replaceAll('\\', '/'));
    } else {
      writeFileSync(target, content);
      console.log(`generated ${relative(frontendDir, target).replaceAll('\\', '/')}`);
    }
  }

  if (check) {
    if (stale.length > 0) {
      console.error(
        `API types are out of date with the committed OpenAPI documents:\n` +
          stale.map((file) => `  ${file}`).join('\n') +
          `\nRun \`npm run gen:api\`, review the diff (it is the API change), adapt the code and the mock handlers.`,
      );
      process.exit(1);
    }
    console.log(`API types match the OpenAPI documents (${SERVICES.length} services).`);
  }
}

await main();
